-- Versões do currículo enviadas pelo upload. O arquivo fica no storage de objetos; aqui só metadados.

create table resume_version (
    id             bigint generated by default as identity primary key,
    label          varchar(120)             not null,
    target_role    varchar(120),
    file_key       varchar(300)             not null unique,
    file_name      varchar(255)             not null,
    content_type   varchar(100)             not null,
    size_bytes     bigint                   not null,
    sha256         varchar(64)              not null unique,
    extracted_text text,
    skills         jsonb,
    is_default     boolean                  not null default false,
    archived       boolean                  not null default false,
    created_at     timestamp with time zone not null default now(),
    constraint resume_version_default_not_archived check (not (is_default and archived))
);

-- No máximo um currículo padrão.
create unique index resume_version_single_default on resume_version (is_default) where is_default;
