-- Relatório semanal de insights, métricas semanais por empresa e notificações.

create table insight_report (
    id                 bigint generated by default as identity primary key,
    period_start       date                     not null,
    period_end         date                     not null,
    top_skills         jsonb                    not null default '[]',
    gaps               jsonb                    not null default '[]',
    funnel             jsonb                    not null default '{}',
    resume_performance jsonb                    not null default '[]',
    suggested_filters  jsonb                    not null default '[]',
    ai_accuracy        numeric(4, 3),
    llm_cost_usd       numeric(10, 4),
    -- sugestões do LLM: lacunas com evidência, bullets reescritos, palavras-chave e o diagnóstico
    recommendations    jsonb,
    model_version      varchar(150)             not null,
    created_at         timestamp with time zone not null default now()
);

create index insight_report_created_idx on insight_report (created_at desc);

create table company_metrics_weekly (
    company_id     bigint      not null references company (id) on delete cascade,
    week_start     date        not null,
    jobs_opened    integer     not null default 0,
    jobs_closed    integer     not null default 0,
    jobs_active    integer     not null default 0,
    reposts        integer     not null default 0,
    avg_days_open  numeric(6, 1),
    by_seniority   jsonb       not null default '{}',
    by_work_model  jsonb       not null default '{}',
    top_skills     jsonb       not null default '[]',
    -- número de funcionários anotado à mão (LinkedIn), para ver a tendência
    headcount      integer,
    primary key (company_id, week_start)
);

alter table company
    add column client_sectors text[] not null default '{}',
    add column contract_types text[] not null default '{}';

-- Republicação: mesma empresa e título parecido.
create index job_title_trgm on job using gin (lower(title) gin_trgm_ops);
create index job_open_idx on job (company_id) where closed_at is null;

create table notification (
    id         bigint generated by default as identity primary key,
    type       varchar(30)              not null,
    title      varchar(300)             not null,
    body       text,
    link       varchar(500),
    -- evita repetir o mesmo alerta (por exemplo, a mesma empresa na mesma semana)
    dedup_key  varchar(200) unique,
    read_at    timestamp with time zone,
    created_at timestamp with time zone not null default now()
);

create index notification_unread_idx on notification (created_at desc) where read_at is null;

-- Falhas seguidas na verificação diária do link (empresas monitoradas); duas fecham a vaga.
alter table job add column link_failures integer not null default 0;
