-- Contatos (recrutadores, headhunters, gestores, quem pode indicar e as conexões do LinkedIn) e o histórico de
-- conversas com eles. Dados mínimos (D-05): nome, empresa, cargo, link do perfil, e-mail só se você anotar e notas.
-- Apagar um contato apaga o histórico dele.

create table contact (
    id            bigint generated by default as identity primary key,
    name          varchar(200)             not null,
    role          varchar(20)              not null
        check (role in ('RECRUTADOR', 'HEADHUNTER', 'GESTOR', 'INDICACAO', 'CONEXAO', 'OUTRO')),
    -- empresa do cadastro casada pelo nome; contato não cria empresa
    company_id    bigint references company (id) on delete set null,
    -- empresa como veio (formulário, export do LinkedIn ou e-mail)
    company_name  varchar(200),
    position      varchar(300),
    linkedin_url  varchar(500) unique,
    email         varchar(320),
    notes         text,
    source        varchar(20)              not null check (source in ('MANUAL', 'LINKEDIN_EXPORT', 'EMAIL')),
    connected_on  date,
    created_at    timestamp with time zone not null default now(),
    updated_at    timestamp with time zone not null default now()
);

create index contact_company_idx on contact (company_id);
create index contact_email_idx on contact (lower(email)) where email is not null;
create index contact_name_trgm on contact using gin (name gin_trgm_ops);

create table contact_interaction (
    id               bigint generated by default as identity primary key,
    contact_id       bigint                   not null references contact (id) on delete cascade,
    application_id   bigint references application (id) on delete set null,
    channel          varchar(20)              not null
        check (channel in ('LINKEDIN', 'EMAIL', 'WHATSAPP', 'TELEFONE', 'PRESENCIAL', 'OUTRO')),
    direction        varchar(10)              not null check (direction in ('ENVIADA', 'RECEBIDA')),
    kind             varchar(30)              not null
        check (kind in ('PEDIDO_INDICACAO', 'FOLLOW_UP', 'AGRADECIMENTO', 'RESPOSTA_RECRUTADOR', 'ABORDAGEM',
                        'CONVERSA', 'OUTRO')),
    summary          text,
    -- e-mail da label de vagas que originou a interação (abordagem de recrutador)
    email_message_id bigint,
    occurred_at      timestamp with time zone not null,
    created_at       timestamp with time zone not null default now()
);

create index contact_interaction_contact_idx on contact_interaction (contact_id, occurred_at desc);
create index contact_interaction_application_idx on contact_interaction (application_id) where application_id is not null;
create unique index contact_interaction_email_idx on contact_interaction (email_message_id) where email_message_id is not null;
