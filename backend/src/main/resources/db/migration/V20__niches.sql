-- Nichos de mercado com subsegmentos, a classificação das empresas e o fit calculado.

create table niche (
    id             bigint generated by default as identity primary key,
    name           varchar(100)             not null unique,
    description    text,
    active         boolean                  not null default true,
    -- pesos do fit: segment, stack, domain e signals, somando 1
    fit_weights    jsonb                    not null,
    -- tipos de empresa que entram no nicho (vazio: qualquer um); Consultorias só aceita CONSULTORIA_TI
    company_kinds  text[]                   not null default '{}',
    -- termos de domínio procurados nas vagas (crédito, antifraude, Pix...)
    domain_terms   text[]                   not null default '{}',
    created_at     timestamp with time zone not null default now()
);

create table niche_segment (
    id                  bigint generated by default as identity primary key,
    niche_id            bigint       not null references niche (id) on delete cascade,
    name                varchar(100) not null,
    description         text,
    base_fit            integer      not null check (base_fit between 0 and 100),
    -- palavras-chave, comparadas sem acento e sem caixa
    keywords            text[]       not null default '{}',
    -- tipos de autorização do Banco Central ou CNAEs da Receita que caem direto neste subsegmento
    authorization_types text[]       not null default '{}',
    unique (niche_id, name)
);

create table company_niche (
    company_id  bigint                   not null references company (id) on delete cascade,
    niche_id    bigint                   not null references niche (id) on delete cascade,
    -- nulo: a empresa fica fora do nicho (decisão sua ou da IA), para a classificação não insistir
    segment_id  bigint references niche_segment (id) on delete cascade,
    source      varchar(10)              not null check (source in ('BCB', 'CNPJ', 'IA', 'VAGA', 'MANUAL')),
    confidence  numeric(3, 2)            not null,
    -- verdadeiro para a sua escolha e para os cadastros oficiais; a sugestão da IA espera a sua confirmação
    verified    boolean                  not null default false,
    assigned_at timestamp with time zone not null,
    primary key (company_id, niche_id)
);

create index company_niche_segment_idx on company_niche (segment_id);

create table company_fit (
    company_id  bigint                   not null references company (id) on delete cascade,
    niche_id    bigint                   not null references niche (id) on delete cascade,
    fit_score   integer                  not null check (fit_score between 0 and 100),
    fit_band    varchar(10)              not null check (fit_band in ('ALTO', 'MEDIO', 'BAIXO')),
    -- notas de 0 a 100 de cada componente, antes dos pesos
    components  jsonb                    not null,
    reasons     jsonb                    not null default '[]',
    computed_at timestamp with time zone not null,
    primary key (company_id, niche_id)
);

create index company_fit_niche_idx on company_fit (niche_id, fit_score desc);

-- Cruzamento com os cadastros públicos. A raiz do CNPJ (8 dígitos) identifica a empresa em todas as filiais e é
-- também o código das instituições no Banco Central.
alter table company
    add column cnpj               varchar(8) unique,
    add column authorization_type varchar(100);
