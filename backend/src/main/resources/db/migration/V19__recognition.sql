-- Selos das empresas (GPTW primeiro), verificados por busca na web e IA, e o cache das buscas.

create table company_recognition (
    id               bigint generated by default as identity primary key,
    company_id       bigint                   not null references company (id) on delete cascade,
    program          varchar(30)              not null default 'GPTW',
    level            varchar(20)              not null
        check (level in ('RANKING_TI', 'RANKING', 'CERTIFICADA', 'EXPIRADA', 'NAO_ENCONTRADA')),
    ranking_name     varchar(200),
    ranking_position integer,
    year             integer,
    valid_until      date,
    evidence_url     varchar(1000),
    -- trecho da evidência e o motivo da IA, mostrados na fila de revisão
    evidence_excerpt text,
    rationale        text,
    -- nome que aparece na evidência; difere do cadastro quando há homônimo ("Stone" e "Stone Pagamentos")
    matched_name     varchar(200),
    confidence       numeric(3, 2)            not null,
    verified_by      varchar(10)              not null check (verified_by in ('IA', 'USUARIO')),
    -- AUTOMATICO: confiança alta e sem homônimo; PENDENTE: na fila de revisão; o selo só aparece em AUTOMATICO e CONFIRMADO
    review_status    varchar(15)              not null
        check (review_status in ('AUTOMATICO', 'PENDENTE', 'CONFIRMADO', 'REJEITADO')),
    source           varchar(15)              not null check (source in ('BUSCA', 'IMPORTACAO')),
    checked_at       timestamp with time zone not null
);

create index company_recognition_company_idx on company_recognition (company_id, checked_at desc);
create index company_recognition_pending_idx on company_recognition (checked_at) where review_status = 'PENDENTE';

-- Selo vigente de cada empresa. O bônus no score da vaga segue RecognitionLevel.bonus().
create view company_gptw as
select distinct on (company_id)
       company_id, level, year, ranking_name, evidence_url,
       case level when 'RANKING_TI' then 10 when 'RANKING' then 7 else 4 end as bonus
from company_recognition
where program = 'GPTW'
  and review_status in ('AUTOMATICO', 'CONFIRMADO')
  and level in ('RANKING_TI', 'RANKING', 'CERTIFICADA')
  and (valid_until is null or valid_until >= current_date)
order by company_id, case level when 'RANKING_TI' then 1 when 'RANKING' then 2 else 3 end, year desc, checked_at desc;

-- Cada consulta paga fica 6 meses em cache; as linhas do mês também contam o limite mensal de consultas.
create table web_search_cache (
    id         bigint generated by default as identity primary key,
    provider   varchar(20)              not null,
    query_hash char(64)                 not null,
    query      text                     not null,
    response   jsonb                    not null,
    fetched_at timestamp with time zone not null,
    unique (provider, query_hash)
);

create index web_search_cache_fetched_idx on web_search_cache (fetched_at);
