-- A vaga normalizada: tudo o que vem de fora (coleta ou cadastro manual) vira uma linha aqui.

create extension if not exists pg_trgm;

create table job (
    id              bigint generated by default as identity primary key,
    -- origem da vaga (MANUAL, alertas por e-mail, ATS...); cresce a cada fonte nova
    source          varchar(40)              not null,
    external_id     varchar(200),
    -- sha256 de empresa + título + localidade normalizados; garante a deduplicação
    fingerprint     varchar(64)              not null unique,
    title           varchar(300)             not null,
    company         varchar(200)             not null,
    location        varchar(200),
    work_model      varchar(20)              not null default 'NAO_INFORMADO'
        check (work_model in ('REMOTO', 'HIBRIDO', 'PRESENCIAL', 'NAO_INFORMADO')),
    salary_range    varchar(100),
    url             varchar(2000),
    raw_description text,
    collected_at    timestamp with time zone not null default now()
);

create unique index job_source_external_id on job (source, external_id) where external_id is not null;
create index job_collected_at_idx on job (collected_at desc);
