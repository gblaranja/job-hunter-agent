-- Execuções da coleta e o lock que garante uma única coleta por vez (ShedLock).

create table collection_run (
    id          bigint generated by default as identity primary key,
    trigger     varchar(10)              not null check (trigger in ('AGENDADA', 'MANUAL')),
    status      varchar(10)              not null check (status in ('RODANDO', 'CONCLUIDA', 'FALHOU')),
    started_at  timestamp with time zone not null,
    finished_at timestamp with time zone,
    -- por fonte: {"GMAIL_ALERTAS": {"new": 3, "duplicate": 1, "excluded": 0, "errors": 0}}
    stats       jsonb                    not null default '{}',
    error       text
);

create index collection_run_started_idx on collection_run (started_at desc);

create table shedlock (
    name       varchar(64)              not null primary key,
    lock_until timestamp with time zone not null,
    locked_at  timestamp with time zone not null,
    locked_by  varchar(255)             not null
);
