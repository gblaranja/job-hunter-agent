-- Currículos adaptados para uma vaga: o texto reescrito pelo LLM a partir do currículo base e da análise da vaga,
-- com a cobertura das palavras-chave antes e depois. Cada vaga pode ter várias versões geradas.

create table tailored_resume (
    id                     bigint generated by default as identity primary key,
    job_id                 bigint                   not null references job (id) on delete cascade,
    base_resume_version_id bigint references resume_version (id) on delete set null,
    -- GERANDO: o LLM está reescrevendo; PRONTO: texto disponível; FALHOU: a geração falhou (last_error)
    status                 varchar(10)              not null check (status in ('GERANDO', 'PRONTO', 'FALHOU')),
    -- currículo completo em Markdown (editável); é a fonte do DOCX
    content                text,
    headline               varchar(300),
    -- principais mudanças: [{section, before, after, reason}]
    changes                jsonb                    not null default '[]',
    -- requisitos da vaga que o currículo base não comprova e por isso não foram adicionados
    not_covered            jsonb                    not null default '[]',
    notes                  text,
    -- palavras-chave da vaga (obrigatórias e desejáveis) e quais aparecem no texto antes e depois
    keywords               jsonb                    not null default '[]',
    covered_before         jsonb                    not null default '[]',
    covered_after          jsonb                    not null default '[]',
    -- skills no texto adaptado que não estão no currículo base: a pessoa precisa confirmar
    unsupported_skills     jsonb                    not null default '[]',
    score_before           integer check (score_before between 0 and 100),
    score_after            integer check (score_after between 0 and 100),
    edited                 boolean                  not null default false,
    -- versão do currículo criada a partir deste texto (o DOCX salvo em Currículos)
    resume_version_id      bigint references resume_version (id) on delete set null,
    model_version          varchar(150),
    last_error             text,
    created_at             timestamp with time zone not null,
    updated_at             timestamp with time zone not null
);

create index tailored_resume_job_idx on tailored_resume (job_id, created_at desc);
-- No máximo uma geração em andamento por vaga.
create unique index tailored_resume_single_generating on tailored_resume (job_id) where status = 'GERANDO';
