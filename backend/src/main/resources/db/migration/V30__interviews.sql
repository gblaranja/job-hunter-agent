-- Entrevistas: o banco de histórias STAR, a preparação gerada para cada etapa e o registro pós-entrevista.

create table star_story (
    id         bigint generated by default as identity primary key,
    title      varchar(200)             not null,
    situation  text                     not null default '',
    task       text                     not null default '',
    action     text                     not null default '',
    result     text                     not null default '',
    -- o que você aprendeu ou faria diferente
    reflection text,
    -- skills que a história comprova, para sugerir a história certa na preparação
    skills     text[]                   not null default '{}',
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

-- Uma preparação por candidatura e etapa; gerar de novo sobrescreve.
create table interview_prep (
    id             bigint generated by default as identity primary key,
    application_id bigint                   not null references application (id) on delete cascade,
    stage          varchar(20)              not null check (stage in ('ENTREVISTA', 'TESTE_TECNICO')),
    -- GERANDO: aguardando a geração; PRONTO: conteúdo disponível; FALHOU: a geração falhou (last_error)
    status         varchar(10)              not null check (status in ('GERANDO', 'PRONTO', 'FALHOU')),
    -- {questions: [{question, reason, storyId, storyTitle, answerOutline}], technicalTopics: [], companyFacts: [],
    --  questionsToAsk: [], pointsToClarify: []}
    content        jsonb,
    -- IA: gerada pela Claude API; REGRAS: montada pelas regras, sem a chave ou depois de uma falha da API
    source         varchar(10) check (source in ('IA', 'REGRAS')),
    model_version  varchar(150),
    last_error     text,
    created_at     timestamp with time zone not null,
    updated_at     timestamp with time zone not null,
    unique (application_id, stage)
);

create table interview_debrief (
    id             bigint generated by default as identity primary key,
    application_id bigint                   not null references application (id) on delete cascade,
    stage          varchar(20)              not null check (stage in ('ENTREVISTA', 'TESTE_TECNICO')),
    interviewed_on date                     not null,
    -- perguntas que fizeram, uma por item; o relatório semanal conta as recorrentes
    questions      jsonb                    not null default '[]',
    went_well      text,
    to_improve     text,
    -- como você avalia a entrevista, de 1 a 5
    rating         smallint check (rating between 1 and 5),
    next_steps     text,
    created_at     timestamp with time zone not null,
    updated_at     timestamp with time zone not null
);

create index interview_debrief_application_idx on interview_debrief (application_id, interviewed_on desc);
