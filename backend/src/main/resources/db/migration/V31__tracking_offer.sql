-- Propostas recebidas: os números para comparar CLT e PJ no mesmo valor equivalente e a decisão.

create table offer (
    id                bigint generated by default as identity primary key,
    application_id    bigint                   not null references application (id) on delete cascade,
    regime            varchar(12)              not null check (regime in ('CLT', 'PJ', 'CONTRACTOR')),
    -- valor-base no período indicado, na moeda indicada
    base_salary       numeric(14, 2)           not null check (base_salary > 0),
    currency          varchar(3)               not null default 'BRL',
    period            varchar(10)              not null default 'MENSAL' check (period in ('MENSAL', 'ANUAL', 'HORA')),
    -- bônus ou PLR esperado no ano, na mesma moeda
    annual_bonus      numeric(14, 2),
    -- benefícios em reais por mês (VR, VA, plano de saúde pago pela empresa)
    monthly_benefits  numeric(14, 2),
    benefits_notes    text,
    equity            text,
    work_model        varchar(20) check (work_model in ('REMOTO', 'HIBRIDO', 'PRESENCIAL', 'NAO_INFORMADO')),
    start_date        date,
    -- até quando a empresa espera a resposta
    respond_by        date,
    decision          varchar(12)              not null default 'PENDENTE'
        check (decision in ('PENDENTE', 'NEGOCIANDO', 'ACEITA', 'RECUSADA')),
    decided_at        timestamp with time zone,
    notes             text,
    created_at        timestamp with time zone not null,
    updated_at        timestamp with time zone not null
);

create index offer_application_idx on offer (application_id);
