-- Dicionário de skills que cresce com revisão (B-22): as skills aceitas nas sugestões complementam o arquivo
-- analysis/skills.txt, e as ignoradas não voltam a ser sugeridas.

create table skill_entry (
    id         bigint generated by default as identity primary key,
    canonical  varchar(100)             not null,
    aliases    text[]                   not null default '{}',
    -- identificador e rótulos da taxonomia europeia ESCO, quando a revisão consultou a API
    esco_uri   varchar(300),
    label_pt   varchar(200),
    label_en   varchar(200),
    created_at timestamp with time zone not null default now()
);

create unique index skill_entry_canonical_idx on skill_entry (lower(canonical));

create table skill_ignored (
    -- nome normalizado (sem acentos, caixa baixa)
    name       varchar(100)             primary key,
    created_at timestamp with time zone not null default now()
);
