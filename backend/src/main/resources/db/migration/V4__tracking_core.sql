-- Candidaturas, histórico do funil e a cópia congelada da vaga aplicada.

create table application (
    id                bigint generated by default as identity primary key,
    job_id            bigint                   not null unique references job (id),
    status            varchar(20)              not null
        check (status in ('NOVA', 'INTERESSE', 'APLICADA', 'TRIAGEM', 'ENTREVISTA', 'TESTE_TECNICO', 'OFERTA',
                          'RECUSADA', 'DESISTI')),
    applied_at        timestamp with time zone,
    channel           varchar(20)
        check (channel in ('EASY_APPLY', 'SITE_EMPRESA', 'INDICACAO', 'EMAIL', 'OUTRO')),
    resume_version_id bigint references resume_version (id),
    notes             text,
    next_action_at    timestamp with time zone,
    created_at        timestamp with time zone not null default now(),
    updated_at        timestamp with time zone not null default now(),
    version           bigint                   not null default 0
);

create index application_status_idx on application (status);
create index application_resume_version_idx on application (resume_version_id);

create table application_event (
    id               bigint generated by default as identity primary key,
    application_id   bigint                   not null references application (id),
    from_status      varchar(20)
        check (from_status in ('NOVA', 'INTERESSE', 'APLICADA', 'TRIAGEM', 'ENTREVISTA', 'TESTE_TECNICO', 'OFERTA',
                               'RECUSADA', 'DESISTI')),
    to_status        varchar(20)
        check (to_status in ('NOVA', 'INTERESSE', 'APLICADA', 'TRIAGEM', 'ENTREVISTA', 'TESTE_TECNICO', 'OFERTA',
                             'RECUSADA', 'DESISTI')),
    response_type    varchar(30)
        check (response_type in ('CONVITE_ENTREVISTA', 'TESTE_TECNICO', 'PEDIDO_INFORMACAO', 'OFERTA', 'RECUSA',
                                 'OUTRO')),
    origin           varchar(10)              not null check (origin in ('MANUAL', 'EMAIL', 'SISTEMA')),
    -- a FK para email_message entra junto com a tabela, na Fase 2
    email_message_id bigint,
    note             text,
    created_at       timestamp with time zone not null default now()
);

create index application_event_application_idx on application_event (application_id, created_at);

-- O histórico é append-only: correções entram como eventos novos, nunca como edição.
create function forbid_application_event_changes() returns trigger
    language plpgsql as
$$
begin
    raise exception 'application_event é append-only: % não é permitido', tg_op;
end;
$$;

create trigger application_event_append_only
    before update or delete
    on application_event
    for each row
execute function forbid_application_event_changes();

create table job_snapshot (
    id                        bigint generated by default as identity primary key,
    application_id            bigint                   not null unique references application (id),
    job_url                   varchar(2000),
    link_status               varchar(20)              not null default 'NAO_VERIFICADO'
        check (link_status in ('ATIVO', 'REMOVIDO', 'NAO_VERIFICADO')),
    link_checked_at           timestamp with time zone,
    link_consecutive_failures integer                  not null default 0,
    title                     varchar(300)             not null,
    company                   varchar(200)             not null,
    description_md            text,
    capture_source            varchar(20)              not null check (capture_source in ('COLETA', 'EXTENSAO', 'MANUAL')),
    page_pdf_key              varchar(300),
    captured_at               timestamp with time zone not null default now()
);

-- Busca por trecho nas vagas aplicadas ("todas que pediam Kafka").
create index job_snapshot_description_trgm on job_snapshot using gin (description_md gin_trgm_ops);
create index job_snapshot_title_trgm on job_snapshot using gin (title gin_trgm_ops);
create index job_snapshot_company_trgm on job_snapshot using gin (company gin_trgm_ops);
