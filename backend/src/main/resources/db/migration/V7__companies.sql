-- Empresas cadastradas a partir das vagas, com aliases para a deduplicação.

create table company (
    id              bigint generated by default as identity primary key,
    name            varchar(200)             not null,
    normalized_name varchar(200)             not null unique,
    website         varchar(500),
    linkedin_url    varchar(500),
    sector          varchar(100),
    size_range      varchar(50),
    hq_location     varchar(200),
    ats_type        varchar(30),
    ats_slug        varchar(200),
    kind            varchar(20)              not null default 'CONTRATANTE'
        check (kind in ('CONTRATANTE', 'CONSULTORIA_TI', 'RECRUTAMENTO')),
    watch_status    varchar(20)              not null default 'DESCOBERTA'
        check (watch_status in ('DESCOBERTA', 'MONITORADA', 'ALVO', 'IGNORADA')),
    notes           text,
    first_seen_at   timestamp with time zone not null default now()
);

create table company_alias (
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references company (id) on delete cascade,
    alias      varchar(200) not null unique
);

alter table job
    add column company_id       bigint references company (id),
    add column first_seen_at    timestamp with time zone,
    add column last_seen_at     timestamp with time zone,
    add column closed_at        timestamp with time zone,
    add column repost_of_job_id bigint references job (id);

update job set first_seen_at = collected_at, last_seen_at = collected_at;
alter table job
    alter column first_seen_at set not null,
    alter column last_seen_at set not null;

create index job_company_idx on job (company_id);
