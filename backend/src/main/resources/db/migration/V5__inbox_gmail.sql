-- Conexão com o Gmail e os e-mails lidos da label "jobs".

-- Tokens OAuth do Google, cifrados com AES-GCM pela aplicação; nunca em texto puro.
create table oauth_credential (
    provider                varchar(30)              not null primary key,
    account_email           varchar(320),
    access_token_enc        text,
    access_token_expires_at timestamp with time zone,
    refresh_token_enc       text                     not null,
    scopes                  text                     not null,
    updated_at              timestamp with time zone not null default now()
);

-- Ponto de sincronização incremental (history.list) por label.
create table gmail_sync_state (
    label_id          varchar(100)             not null primary key,
    last_history_id   numeric(30)              not null,
    last_full_sync_at timestamp with time zone not null
);

-- O corpo do e-mail não é guardado: quando preciso, é buscado no Gmail pelo gmail_id.
create table email_message (
    id                   bigint generated by default as identity primary key,
    gmail_id             varchar(100)             not null unique,
    thread_id            varchar(100),
    application_id       bigint references application (id),
    sender               varchar(320)             not null,
    subject              varchar(1000),
    snippet              varchar(1000),
    received_at          timestamp with time zone not null,
    kind                 varchar(10)              not null check (kind in ('ALERTA', 'OUTRO')),
    parsed_at            timestamp with time zone,
    jobs_found           integer,
    ai_classification    varchar(30),
    ai_confidence        numeric(4, 3),
    final_classification varchar(30),
    classified_by        varchar(10) check (classified_by in ('IA', 'USUARIO')),
    processed            boolean                  not null default false,
    created_at           timestamp with time zone not null default now()
);

create index email_message_pending_alerts on email_message (received_at) where kind = 'ALERTA' and parsed_at is null;

alter table application_event
    add constraint application_event_email_message_fk foreign key (email_message_id) references email_message (id);
