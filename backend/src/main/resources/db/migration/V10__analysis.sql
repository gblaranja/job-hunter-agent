-- Análise das vagas: requisitos extraídos, score de aderência e o uso da API do LLM.

create table job_analysis (
    job_id              bigint                   not null primary key references job (id) on delete cascade,
    -- DETERMINISTICO: só dicionário e regras; COMPLETO: refinado pelo LLM;
    -- PENDENTE: aguardando a etapa do LLM; FALHOU: o LLM falhou e será tentado de novo
    status              varchar(15)              not null
        check (status in ('DETERMINISTICO', 'PENDENTE', 'COMPLETO', 'FALHOU')),
    seniority           varchar(20),
    required_skills     jsonb                    not null default '[]',
    nice_to_have        jsonb                    not null default '[]',
    work_model          varchar(20),
    summary             text,
    employer_kind       varchar(20),
    client_sectors      jsonb                    not null default '[]',
    contract_type       varchar(20),
    resume_version_id   bigint references resume_version (id) on delete set null,
    deterministic_score integer,
    llm_adjustment      integer,
    match_score         integer check (match_score between 0 and 100),
    matched_skills      jsonb                    not null default '[]',
    gaps                jsonb                    not null default '[]',
    justification       text,
    model_version       varchar(150)             not null,
    attempts            integer                  not null default 0,
    next_attempt_at     timestamp with time zone,
    last_error          text,
    analyzed_at         timestamp with time zone not null
);

-- "Vagas que pedem Kafka" sem modelo relacional de skills.
create index job_analysis_required_skills_gin on job_analysis using gin (required_skills jsonb_path_ops);
create index job_analysis_pending_idx on job_analysis (next_attempt_at) where status in ('PENDENTE', 'FALHOU');
create index job_analysis_score_idx on job_analysis (match_score desc nulls last);

-- Cada chamada ao LLM, para acompanhar custo e acerto do cache.
create table llm_usage (
    id                 bigint generated by default as identity primary key,
    task               varchar(40)              not null,
    model              varchar(60)              not null,
    input_tokens       integer                  not null,
    output_tokens      integer                  not null,
    cache_read_tokens  integer                  not null default 0,
    cache_write_tokens integer                  not null default 0,
    created_at         timestamp with time zone not null default now()
);

create index llm_usage_created_idx on llm_usage (created_at);
